lista_de_lista = [['a', 'b', 'c'], [5, 8, 2], []]

print(lista_de_lista)  # [['a', 'b', 'c'], [5, 8, 2], []]
print(lista_de_lista[0])  # ['a', 'b', 'c']
print(lista_de_lista[0][1])  # b
print(len(lista_de_lista))  # len() retorna o tamanho de um objeto
print(lista_de_lista[-1])  # em python o -1 retorna o último elemento da lista
