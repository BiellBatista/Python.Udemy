# -*- coding: utf-8 -*-

lista = [1, 2, 8, 5, 15, 3, 6, 8]
# lista sempre estará delimitada por []
print(lista)

print(lista[5])  # pegando o quinto elemento (0 1 2 3 4 5)

l = ['a', 'b', 'c', 'd', 'e']
print(l)

lista1 = list("eXcript")  #cada caracter vira um elemento da lista
print(lista1)  # ['e', 'X', 'c', 'r', 'i', 'p', 't']

lista2 = list((4, 5, 8))
print(lista2)  # [4, 5, 8]

lista3 = list(("eXcript", "Gabriel"))  # uma lista com dois elementos do tipo string
print(lista3)
